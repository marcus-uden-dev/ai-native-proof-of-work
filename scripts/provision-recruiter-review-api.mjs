import { spawn } from 'node:child_process';
import { existsSync } from 'node:fs';
import { mkdtemp, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const workerDirectory = join(root, 'workers', 'recruiter-review');
const configPath = join(root, 'site', 'assets', 'js', 'recruiter-review-config.js');
const wrangler = ['--yes', 'wrangler@4.129.0'];
const npx = process.platform === 'win32' ? process.execPath : 'npx';
const npxPrefix = process.platform === 'win32'
  ? [join(dirname(process.env.npm_execpath ?? join(process.execPath, '..', 'node_modules', 'npm', 'bin', 'npm-cli.js')), 'npx-cli.js')]
  : [];
const npxArgs = (args) => [...npxPrefix, ...args];

const whoami = await run(npx, npxArgs([...wrangler, 'whoami']), { allowFailure: true });
if (whoami.exitCode !== 0 || /not authenticated/i.test(whoami.output)) {
  await loginToCloudflare();
}

const key = await readSecret('Paste GROQ_API_KEY: ');
if (!key) throw new Error('GROQ_API_KEY cannot be empty. No deployment was made.');

const directory = await mkdtemp(join(tmpdir(), 'recruiter-review-'));
const secretsPath = join(directory, '.env');
try {
  await writeFile(secretsPath, `GROQ_API_KEY=${JSON.stringify(key)}\n`, { mode: 0o600 });
  const deployed = await run(npx, npxArgs([...wrangler, 'deploy', '--cwd', workerDirectory, '--secrets-file', secretsPath]));
  const endpoint = deployed.output.match(/https:\/\/[^\s]+\.workers\.dev/)?.[0];
  if (!endpoint) throw new Error('Worker deployed but no workers.dev URL was found. Copy the URL from Wrangler output into site/assets/js/recruiter-review-config.js.');
  await writeFile(configPath, `// Generated by npm run review-api:provision. This file contains no secret.\nwindow.RECRUITER_REVIEW_API = { endpoint: ${JSON.stringify(endpoint)} };\n`);
  console.log(`Worker deployed at ${endpoint}`);
  console.log('Static-site configuration updated. Commit and deploy this branch through main to enable the live textbox.');
} finally {
  await rm(directory, { recursive: true, force: true });
}

async function readSecret(prompt) {
  if (!process.stdin.isTTY || !process.stdin.setRawMode) {
    throw new Error('GROQ_API_KEY must be entered from an interactive terminal.');
  }

  process.stdout.write(prompt);
  const wasRaw = process.stdin.isRaw;
  process.stdin.setRawMode(true);
  process.stdin.resume();

  return new Promise((resolvePromise, reject) => {
    let value = '';
    const finish = () => {
      process.stdin.off('data', onData);
      process.stdin.setRawMode(wasRaw);
      process.stdin.pause();
    };
    const onData = (chunk) => {
      for (const character of chunk.toString('utf8')) {
        if (character === '\r' || character === '\n') {
          finish();
          process.stdout.write('\n');
          resolvePromise(value.trim());
          return;
        }
        if (character === '\u0003') {
          finish();
          process.stdout.write('\n');
          reject(new Error('GROQ_API_KEY entry cancelled. No deployment was made.'));
          return;
        }
        if (character === '\b' || character === '\u007f') value = value.slice(0, -1);
        else if (character >= ' ') value += character;
      }
    };
    process.stdin.on('data', onData);
  });
}

function run(command, args, { allowFailure = false, inherit = false } = {}) {
  return new Promise((resolvePromise, reject) => {
    const child = spawn(command, args, { cwd: root, shell: false, stdio: inherit ? 'inherit' : ['ignore', 'pipe', 'pipe'] });
    let output = '';
    if (!inherit) {
      child.stdout.on('data', (chunk) => { output += chunk; process.stdout.write(chunk); });
      child.stderr.on('data', (chunk) => { output += chunk; process.stderr.write(chunk); });
    }
    child.on('error', reject);
    child.on('close', (exitCode) => {
      if (exitCode !== 0 && !allowFailure) reject(new Error(`${command} ${args.join(' ')} failed with exit code ${exitCode}`));
      else resolvePromise({ exitCode, output });
    });
  });
}

async function loginToCloudflare() {
  let output = '';
  let chromeOpened = false;
  await new Promise((resolvePromise, reject) => {
    const child = spawn(npx, npxArgs([...wrangler, 'login', '--browser=false']), { cwd: root, shell: false, stdio: ['ignore', 'pipe', 'pipe'] });
    const report = (chunk) => {
      const text = chunk.toString();
      output += text;
      process.stdout.write(text);
      if (!chromeOpened) {
        const url = output.match(/https:\/\/dash\.cloudflare\.com\/oauth2\/auth\?[^\s]+/)?.[0];
        if (url) chromeOpened = openInChrome(url);
      }
    };
    child.stdout.on('data', report);
    child.stderr.on('data', report);
    child.on('error', reject);
    child.on('close', (exitCode) => {
      if (exitCode !== 0) reject(new Error(`Cloudflare login failed with exit code ${exitCode}`));
      else resolvePromise();
    });
  });
}

function openInChrome(url) {
  const chrome = 'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe';
  if (!existsSync(chrome)) return false;
  const child = spawn(chrome, [url], { detached: true, shell: false, stdio: 'ignore' });
  child.unref();
  return true;
}
